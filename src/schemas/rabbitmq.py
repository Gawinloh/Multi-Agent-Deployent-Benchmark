"""RabbitMQ configuration schemas.

Pure data containers plus a render method, matching the shape of the
postgres/nginx/redis schemas. Authoritative sources:

- Resource limits: RabbitMQ docs "Memory Alarms"
  (https://www.rabbitmq.com/docs/memory) and "Disk Alarms"
  (https://www.rabbitmq.com/docs/disk-alarms).
- Listeners / networking: RabbitMQ docs "Networking"
  (https://www.rabbitmq.com/docs/networking).
- Security: RabbitMQ docs "Access Control"
  (https://www.rabbitmq.com/docs/access-control), "Production Checklist"
  (https://www.rabbitmq.com/docs/production-checklist), and "TLS Support"
  (https://www.rabbitmq.com/docs/ssl).

Output is the modern sysctl-style ``rabbitmq.conf`` (key = value), not
the classic Erlang-terms ``rabbitmq.config``, which RabbitMQ has
deprecated.
"""

from __future__ import annotations

import re

from pydantic import BaseModel, Field, field_validator, model_validator


def _rmq_bool(value: bool) -> str:
    return "true" if value else "false"


class RabbitMQResourceParams(BaseModel):
    """Memory and disk alarm thresholds.

    Source: RabbitMQ "Memory Alarms" — when the broker's memory use
    exceeds ``vm_memory_high_watermark`` it blocks publishing connections
    until consumers catch up. "Disk Alarms" — ``disk_free_limit`` does
    the same for free disk space, and the docs recommend at least one
    times RAM for a node that pages messages out.
    """

    #: Fraction of available RAM, the form the docs recommend over an
    #: absolute value because it survives the node being moved hosts.
    vm_memory_high_watermark: float = Field(
        gt=0, le=1, description="fraction of available RAM, e.g. 0.4"
    )
    #: Paging begins at this fraction *of the watermark*, not of RAM.
    vm_memory_high_watermark_paging_ratio: float = Field(
        default=0.5, gt=0, le=1, description="fraction of the watermark"
    )
    disk_free_limit: str = Field(
        pattern=r"^\d+(\.\d+)?\s?(kb|mb|gb|KB|MB|GB|kB|MB|GB)?$",
        description='absolute free-disk floor, e.g. "2GB"',
    )


class RabbitMQNetworkingParams(BaseModel):
    """Listener ports and connection limits.

    Source: RabbitMQ "Networking" — AMQP 0-9-1 listens on 5672 by
    default and 5671 for TLS; ``listeners.tcp.*`` controls the interface
    the plaintext listener binds to.
    """

    listener_port: int = Field(default=5672, gt=0, le=65535)
    #: Interface for the plaintext AMQP listener. The production
    #: checklist recommends an internal interface rather than a wildcard.
    listener_ip: str = Field(default="0.0.0.0", min_length=1)
    #: Cap on simultaneous client connections; None leaves it unlimited.
    max_connections: int | None = Field(default=None, gt=0)
    heartbeat: int = Field(
        default=60, ge=0, description="seconds; 0 disables heartbeats"
    )


class RabbitMQSecurityParams(BaseModel):
    """Authentication, the default account, and TLS.

    Source: RabbitMQ "Production Checklist" — the ``guest`` account must
    not survive into production; "Access Control" — ``default_user`` /
    ``default_pass`` name the single user seeded on a node's first boot,
    and ``loopback_users`` restricts an account to loopback connections;
    "TLS Support" — ``listeners.ssl.*`` plus ``ssl_options.*``.
    """

    #: The user seeded on first boot. Naming anything other than "guest"
    #: means the well-known default account is never created at all.
    default_user: str = Field(min_length=1)
    default_pass: str = Field(min_length=8)
    #: Users restricted to loopback connections. RabbitMQ ships with
    #: ["guest"]; an empty list removes that restriction and is the
    #: classic misconfiguration.
    loopback_users: list[str] = Field(default_factory=lambda: ["guest"])
    #: Enable the TLS (AMQPS) listener on `tls_port`. Certificates are
    #: generated by the harness, as they are for postgres.
    tls_enabled: bool = False
    tls_port: int = Field(default=5671, gt=0, le=65535)
    #: Reject clients that present no certificate. Only meaningful with
    #: tls_enabled.
    tls_verify_peer: bool = False

    @field_validator("default_user")
    @classmethod
    def _check_default_user(cls, v: str) -> str:
        if re.search(r"\s", v):
            raise ValueError("default_user must not contain whitespace")
        return v


class RabbitMQManagementParams(BaseModel):
    """The management plugin's HTTP listener.

    Source: RabbitMQ "Management Plugin"
    (https://www.rabbitmq.com/docs/management) — the UI and HTTP API
    listen on 15672. The production checklist treats exposing that
    listener on a public interface as a finding, since it is a full
    administrative surface.
    """

    enabled: bool = True
    port: int = Field(default=15672, gt=0, le=65535)
    #: Interface the management listener binds to. "127.0.0.1" keeps the
    #: administrative surface off the network.
    listener_ip: str = Field(default="127.0.0.1", min_length=1)


class RabbitMQConfig(BaseModel):
    """Complete rabbitmq.conf specification."""

    resources: RabbitMQResourceParams
    networking: RabbitMQNetworkingParams
    security: RabbitMQSecurityParams
    management: RabbitMQManagementParams

    @model_validator(mode="after")
    def _check_listener_ports_differ(self) -> RabbitMQConfig:
        """A TLS listener cannot share the plaintext listener's port.

        RabbitMQ would fail to bind the second listener and the node
        would not start, which the agent then has to diagnose from a
        container log rather than from a validation error.
        """
        ports = [self.networking.listener_port, self.management.port]
        if self.security.tls_enabled:
            ports.append(self.security.tls_port)
        if len(set(ports)) != len(ports):
            raise ValueError(
                "listener_port, tls_port and management.port must all differ; "
                f"got {ports}"
            )
        return self

    def render_conf(self) -> str:
        """Render a rabbitmq.conf text body (sysctl format)."""
        lines = [
            "# rabbitmq.conf - generated, do not edit by hand",
            "# sysctl format (RabbitMQ 3.7+); the classic Erlang-terms",
            "# rabbitmq.config format is deprecated.",
            "",
            "# --- Listeners (RabbitMQ Networking docs) ---",
            f"listeners.tcp.default = {self.networking.listener_ip}:"
            f"{self.networking.listener_port}",
            f"heartbeat = {self.networking.heartbeat}",
        ]
        if self.networking.max_connections is not None:
            # `max_connections`, not the older `connection_max`: RabbitMQ 4
            # accepts the latter but logs a rename warning on every boot.
            lines.append(f"max_connections = {self.networking.max_connections}")

        lines += [
            "",
            "# --- Resource alarms (RabbitMQ Memory/Disk Alarms docs) ---",
            "vm_memory_high_watermark.relative = "
            f"{self.resources.vm_memory_high_watermark}",
            "vm_memory_high_watermark_paging_ratio = "
            f"{self.resources.vm_memory_high_watermark_paging_ratio}",
            f"disk_free_limit.absolute = {self.resources.disk_free_limit}",
            "",
            "# --- Default account (RabbitMQ Production Checklist) ---",
            f"default_user = {self.security.default_user}",
            f"default_pass = {self.security.default_pass}",
        ]
        # An empty list must still be emitted: writing no loopback_users
        # line at all leaves RabbitMQ's built-in ["guest"] in force, so
        # silence would misrepresent the specification.
        if self.security.loopback_users:
            for user in self.security.loopback_users:
                lines.append(f"loopback_users.{user} = true")
        else:
            lines.append("loopback_users = none")

        lines += [
            "",
            "# --- TLS (RabbitMQ TLS Support docs) ---",
        ]
        if self.security.tls_enabled:
            lines += [
                f"listeners.ssl.default = {self.security.tls_port}",
                "ssl_options.cacertfile = /etc/rabbitmq/certs/ca.crt",
                "ssl_options.certfile = /etc/rabbitmq/certs/server.crt",
                "ssl_options.keyfile = /etc/rabbitmq/certs/server.key",
                "ssl_options.verify = "
                f"{'verify_peer' if self.security.tls_verify_peer else 'verify_none'}",
                "ssl_options.fail_if_no_peer_cert = "
                f"{_rmq_bool(self.security.tls_verify_peer)}",
            ]
        else:
            lines.append("# TLS listener not enabled by this specification")

        lines += [
            "",
            "# --- Management plugin (RabbitMQ Management docs) ---",
        ]
        if self.management.enabled:
            lines.append(
                f"management.tcp.ip = {self.management.listener_ip}"
            )
            lines.append(f"management.tcp.port = {self.management.port}")
        else:
            lines.append("# management listener not configured by this specification")

        lines.append("")
        return "\n".join(lines)
